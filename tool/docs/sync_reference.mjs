// Generate every machine-readable documentation view from canonical Markdown.
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { capabilityViews, protocolViews } from './reference_views.mjs';
import { verifyPublishedProof } from './rendered_example.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const check = process.argv.includes('--check');
let drift = 0;
await syncInterfaces();
async function* walk(dir) {
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (entry.name.endsWith('.md') && entry.name !== 'README.md') yield path;
  }
}
const pages = [];
for await (const file of walk(join(root, 'documentation'))) {
  const body = await readFile(file, 'utf8');
  const path = relative(join(root, 'documentation'), file).replaceAll('\\', '/');
  pages.push({ path, title: body.match(/^#\s+(.+)$/m)?.[1] ?? path, body });
}
const version = (await readFile(join(root, 'packages/fluvie_cli/pubspec.yaml'), 'utf8')).match(/^version:\s*(.+)$/m)[1];
const json = JSON.stringify(pages);
const digest = createHash('sha256').update(json).digest('hex');
const encoded = Buffer.from(json).toString('base64');
const mapPath = 'documentation/README.md';
const mapSource = await readFile(join(root, mapPath), 'utf8');
const mapRegion = /<!-- generated-doc-map:start -->[\s\S]*?<!-- generated-doc-map:end -->/;
if (!mapRegion.test(mapSource)) throw new Error('Missing generated documentation map markers');
const mapRows = pages.map((page) =>
  `| ${page.path.includes('/') ? dirname(page.path) + '/' : '(root)'} | [${page.title.replaceAll('|', '\\|')}](${page.path}) |`);
await output(mapPath, mapSource.replace(mapRegion,
  '<!-- generated-doc-map:start -->\n' +
  '<!-- Generated by tool/docs/sync_reference.mjs; edit the linked pages. -->\n' +
  '| Section | Page |\n| --- | --- |\n' + mapRows.join('\n') +
  '\n<!-- generated-doc-map:end -->'));
await output('packages/fluvie_cli/lib/src/docs/documentation_bundle.g.dart',
  '// GENERATED by tool/docs/sync_reference.mjs; edit documentation/ instead.\n' +
  `const String bundledDocumentationVersion = '${version}';\n` +
  `const String bundledDocumentationDigest =\n    '${digest}';\n` +
  'const String bundledDocumentationBase64 =\n' +
  encoded.match(/.{1,96}/g).map((chunk) => `    '${chunk}'`).join('\n') + ';\n');
const llms = `# Fluvie ${version}\n\nFlutter widgets become reproducible video. Canonical documentation is generated from the same versioned source as the CLI and MCP bundle.\n\n## Start here\n\n- [AI authoring entry page](https://fluvie.dev/for-ai): prompt template, quick or guided workflow, and direct links for assistants.\n- [Portable Fluvie video skill](https://fluvie.dev/skills/fluvie-video/SKILL.md): end-to-end workflow for a new or existing project; MCP is optional.\n- [AI video authoring guide](https://docs.fluvie.dev/guides/ai-video-authoring/): choose direct creation or approval checkpoints.\n- [Create a video from local assets](https://docs.fluvie.dev/getting-started/authoring-with-assets/): project setup, asset inspection, preview, and MP4 output.\n- Local agents: run \`fluvie docs --context\` for version-matched offline guidance.\n- [Offline complete documentation](https://docs.fluvie.dev/llms-full.txt): use when a focused page is not enough.\n\n## Documentation\n\n` +
  pages.map((page) => `- [${page.title}](https://docs.fluvie.dev/${page.path === 'index.md' ? '' : `${page.path.slice(0, -3)}/`})`).join('\n') + '\n';
for (const app of ['docs', 'site']) {
  await output(`web/${app}/public/llms.txt`, llms);
  await output(`web/${app}/public/llms-full.txt`, `# Fluvie ${version} documentation\n\nCorpus SHA-256: ${digest}\n\n` + pages.map((page) => `<!-- source: documentation/${page.path} -->\n${page.body}`).join('\n\n'));
  await output(`web/${app}/public/skills/fluvie-video/SKILL.md`,
    await readFile(join(root, '.agents/skills/fluvie-video/SKILL.md'), 'utf8'));
}
const snippetSource = await readFile(join(root, 'examples/gallery/lib/snippets/authoring_snippets.dart'), 'utf8');
function snippet(region) {
  const match = snippetSource.match(new RegExp(`// #docregion ${region}\\n([\\s\\S]*?)// #enddocregion ${region}`));
  if (!match) throw new Error(`Missing compiled website snippet: ${region}`);
  return match[1].replace(/^\/\/\/.*\n/, '').trim();
}
await output('web/site/src/generated/ai-example.txt', snippet('website-promo') + '\n');
await output('web/site/public/media/promo.dart',
  "import 'package:flutter/material.dart' hide Animation, Clip, Image, Tween;\n" +
  "import 'package:fluvie/fluvie.dart';\n\n" +
  snippet('website-promo').replace('Video promo()', 'Video build()') + '\n');
await output('web/site/src/generated/start-example.txt',
  "import 'package:flutter/material.dart' hide Animation, Clip, Image, Tween;\n" +
  "import 'package:fluvie/fluvie.dart';\n\n" +
  snippet('website-start').replace('Video startExample()', 'Video build()') + '\n');
if (!process.argv.includes('--skip-rendered-proof')) {
  const media = join(root, 'web/site/public/media');
  const [proof, source, video, poster] = await Promise.all([
    readFile(join(media, 'promo.render.json'), 'utf8'),
    ...['promo.dart', 'promo.mp4', 'promo.poster.png'].map((name) => readFile(join(media, name))),
  ]);
  verifyPublishedProof(JSON.parse(proof), source, video, poster);
}
console.log(`${check ? 'checked' : 'generated'} ${pages.length} canonical pages (${version}, ${digest.slice(0, 12)})`);
if (drift) process.exitCode = 1;

async function output(path, content) {
  const absolute = join(root, path);
  const existing = await readFile(absolute, 'utf8').catch(() => undefined);
  if (existing === content) return;
  if (check) {
    console.error(`Documentation view is stale: ${path}`);
    drift++;
  } else {
    await mkdir(dirname(absolute), { recursive: true });
    await writeFile(absolute, content);
  }
}

async function syncInterfaces() {
  function exportDart(path) {
    return JSON.parse(execFileSync('dart', ['--packages=.dart_tool/package_config.json', path],
      { cwd: root, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 }));
  }
  async function interfaceReference(name, exporter) {
    const path = `tool/docs/generated/${name}.json`;
    if (process.argv.includes('--export-interfaces')) {
      const reference = exportDart(exporter);
      await output(path, JSON.stringify(reference, null, 2) + '\n');
      return reference;
    }
    return JSON.parse(await readFile(join(root, path), 'utf8'));
  }
  const protocol = await interfaceReference('server-protocol',
    'packages/fluvie_server/tool/export_protocol_reference.dart');
  const views = protocolViews(protocol);
  await output('web/site/src/generated/http-example.txt', views.http + '\n');
  await output('web/site/src/generated/mcp-example.txt', views.mcp + '\n');
  await output('documentation/reference/server-protocol.md',
    '# Server protocol\n\n' +
    'These examples are exported from the HTTP request serializer, server parser and MCP tool registry. ' +
    'Run a configured Fluvie server first, then set `FLUVIE_API_URL` and `FLUVIE_API_TOKEN`. ' +
    'The token authenticates to your Fluvie server; the server configures its authoring provider separately.\n\n' +
    '## HTTP render request\n\n```sh\n' + views.http + '\n```\n\n' +
    'The server returns HTTP 202 and a job. Poll the job URL in the `Location` header until it succeeds, then read its video download URL. ' +
    'A prompt request requires a configured authoring provider. Use a code, spec or registered key request when the composition is already authored.\n\n' +
    '## MCP tool call\n\n' +
    'Initialize your MCP session and send this `tools/call` message through the configured stdio or HTTP transport.\n\n```json\n' +
    views.mcp + '\n```\n\n## Render tools\n\n' +
    '| Tool | Arguments | Purpose |\n| --- | --- | --- |\n' + views.tools + '\n\n' +
    '## Where to next\n\n- [AI and MCP](../guides/ai-and-mcp.md): configuration and docs-mode tools.\n' +
    '- [Rendering on a server](../guides/rendering-on-a-server.md): hosting and job lifecycle.\n');
  const capabilities = await interfaceReference('render-capabilities',
    'packages/fluvie_media/tool/render_capabilities.dart');
  const capability = capabilityViews(capabilities);
  for (const backend of capabilities.backends) {
    for (const evidence of backend.evidence) await readFile(join(root, evidence));
  }
  await output('documentation/reference/render-capabilities.md',
    '# Render capabilities\n\n' +
    'The shared backend registry drives render preflight and this table. It describes library support, ' +
    'not a guarantee that a codec or host exists on every device. Choose supported settings before capture; ' +
    'unsupported requests fail with a capability diagnostic. Custom renderers provide their own profile.\n\n' +
    capability.table + '\n\n' + capability.notes + '\n\n' +
    'A “no” for an owned snapshot host means the adapter does not provide that host by default. ' +
    'A suitable custom host can supply additional capabilities explicitly.\n\n' +
    '## Where to next\n\n- [The rendering surface](rendering-surface.md): custom render requests and adapters.\n' +
    '- [Exporting your video](../guides/exporting-your-video.md): select an output.\n');
  for (const app of ['docs', 'site']) {
    await output(`web/${app}/public/render-capabilities.json`, JSON.stringify(capabilities, null, 2) + '\n');
    await output(`web/${app}/public/server-protocol.json`, JSON.stringify(protocol, null, 2) + '\n');
  }
}
